import { supabase } from './supabase.js';

// Усё пра баны, што трэба ведаць старонкам сайта.
//
// Тэксты прычын жывуць тут, а не ў базе: база трымае кароткі код ('hate',
// 'personal', 'spam', 'rules'), бо адну і тую ж прычыну трэба паказаць двойчы
// і па-рознаму — мадэратару спісам, а чалавеку сказам, дзе яна стаіць у
// склоне. Два выгляды аднаго — гэта праца мовы, і ёй месца ў кодзе сайта.
//
// «Іншага» сярод прычын няма наўмысна: бан па прычыне «іншае» не тлумачыць
// нічога, а чалавек мусіць ведаць, што менавіта рабіў не так.
const BAN_REASONS = [
    { id: 'hate', label: 'мова варожасці', phrase: 'за мову варожасці' },
    {
        id: 'personal',
        label: 'чужыя асабістыя дадзеныя',
        phrase: 'за выкарыстанне чужых асабістых дадзеных',
    },
    { id: 'spam', label: 'спам', phrase: 'за спам' },
    {
        id: 'rules',
        label: 'сістэматычнае парушэнне правілаў',
        phrase: 'за сістэматычнае парушэнне правілаў',
    },
];

const find = (code) => BAN_REASONS.find((reason) => reason.id === code);

// Не знайшлі код — паказваем яго сам: лепш незразумелае слова, чым пусты
// радок, па якім не зразумець, ці ёсць там наогул прычына.
const banLabel = (code) => find(code)?.label || code || '';

// А ў сказе пусты радок лепш за код: «ты ў бане да 4 верасня hate» —
// горш, чым проста «ты ў бане да 4 верасня».
const banPhrase = (code) => find(code)?.phrase || '';

// Свой уласны бан — ці няма яго.
//
// Пытаемся адзін раз на загрузку старонкі і запамінаем: пытанне ўзнікае і ў
// профілі ў шапцы, і на старонцы дадавання слова, а адказ на ўсёй старонцы
// адзін і той жа.
let asked = null;

function myBan() {
    if (asked) {
        return asked;
    }

    asked = (async () => {
        const { data, error } = await supabase.rpc('my_ban');

        // Памылка тут — гэта «няма такой функцыі» ці «няма правоў». І тое і
        // другое чытаем як «не забанены»: маўчаць бяспечней, чым сказаць
        // чалавеку, што ён у бане, калі мы гэтага не ведаем.
        if (error) {
            return null;
        }

        return (data && data[0]) || null;
    })();

    return asked;
}

// Пасля ўваходу ці выхаду адказ ужо не той — пытаемся нанова.
function forgetMyBan() {
    asked = null;
}

export { BAN_REASONS, banLabel, banPhrase, myBan, forgetMyBan };
