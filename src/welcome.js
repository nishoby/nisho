// Што сказаў ліст-пацверджанне.
//
// Supabase вяртае чалавека на сайт і кладзе адказ у хвост адраса:
// «#access_token=...&type=signup» — калі ўсё добра, і «#error=...» — калі
// спасылка састарэла. А потым сам жа гэты хвост прыбірае, як толькі разбярэ.
//
// Таму чытаем адрас да таго, як кліент паспее гэта зрабіць: файл падключаны
// першым радком у main.js, раней за ўсё астатняе.
const hash = typeof window === 'undefined' ? '' : window.location.hash || '';

const has = (what) => new RegExp('(^|[#&])' + what + '(=|&|$)').test(hash);

// Пацверджанне пошты — не любы ўваход. Пасля звычайнага логіна вітацца
// няма з чым: чалавек тут не ўпершыню.
const confirmed = has('type=signup');

// Спасылкі жывуць не вечна, і састарэлая — самы частая непрыемнасць. Маўчаць
// пра яе нельга: чалавек націснуў у лісце, вярнуўся на сайт, і нічога не
// адбылося — ён вырашыць, што зламаўся сайт, а не спасылка.
const expired = has('error');

// Аддаём адзін раз: паведамленне мусіць з'явіцца пры вяртанні, а не пры
// кожным пераходзе па сайце ў тым жа акне.
let taken = false;

function takeGreeting() {
    if (taken) {
        return null;
    }

    taken = true;

    if (confirmed) {
        return 'welcome';
    }

    if (expired) {
        return 'expired';
    }

    return null;
}

export { takeGreeting };
